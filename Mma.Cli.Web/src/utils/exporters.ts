import { ENGINE_PROFILES, formatTypeForEngine, convertDefaultValueForEngine } from '../data/engines';
import {
  Column,
  DatabaseEngine,
  normalizeTableCodeGen,
  Relation,
  SchemaModel,
  SqlDialect,
  Table,
  TableCheckConstraint,
  TableIndex,
  TableUniqueConstraint,
} from '../types/schema';

export interface SqlExportOptions {
  dialect: SqlDialect;
  includeDropTable: boolean;
  includeComments: boolean;
  quoteIdentifiers: boolean;
}

function quoteId(name: string, dialect: SqlDialect, enabled: boolean): string {
  const clean = name.trim() || 'unnamed';
  if (!enabled) return clean;
  const [open, close] = ENGINE_PROFILES[dialect].identifierQuotes;
  return `${open}${clean}${close}`;
}

function escapeSqlString(str: string): string {
  return str.replace(/'/g, "''");
}

function formatTableName(table: Table, dialect: SqlDialect, quoteIdentifiers: boolean): string {
  const profile = ENGINE_PROFILES[dialect];
  const rawSchema = (table.schema || '').trim();
  const effectiveSchema =
    dialect === 'mssql'
      ? rawSchema || 'dbo'
      : profile.supportsSchemaNamespace
      ? rawSchema
      : '';

  const tbl = quoteId(table.name, dialect, quoteIdentifiers);
  if (effectiveSchema && !(dialect === 'postgresql' && effectiveSchema === 'public')) {
    return `${quoteId(effectiveSchema, dialect, quoteIdentifiers)}.${tbl}`;
  }
  return tbl;
}

export function generateSqlDDL(schema: SchemaModel, options: SqlExportOptions): string {
  const { dialect, includeDropTable, includeComments, quoteIdentifiers } = options;
  const profile = ENGINE_PROFILES[dialect];
  const lines: string[] = [];

  lines.push(`-- Schema: ${schema.name}`);
  lines.push(`-- Engine: ${profile.label}`);
  if (schema.description) {
    lines.push(`-- Description: ${schema.description}`);
  }
  lines.push('-- Generated by SchemaForge');
  lines.push('');

  const tableMap = new Map<string, Table>();
  schema.tables.forEach((t) => tableMap.set(t.id, t));

  if (includeDropTable && schema.tables.length > 0) {
    [...schema.tables].reverse().forEach((table) => {
      const tblName = formatTableName(table, dialect, quoteIdentifiers);
      const cascade = dialect === 'postgresql' ? ' CASCADE' : '';
      lines.push(`DROP TABLE IF EXISTS ${tblName}${cascade};`);
    });
    if (dialect === 'mssql') {
      lines.push('GO');
    }
    lines.push('');
  }

  const alterFkStatements: string[] = [];
  const indexStatements: string[] = [];
  const joinTableStatements: string[] = [];

  const getFkForTable = (
    tableId: string
  ): { rel: Relation; srcTable: Table; srcCols: Column[]; tgtCols: Column[] }[] => {
    const result: { rel: Relation; srcTable: Table; srcCols: Column[]; tgtCols: Column[] }[] = [];
    for (const rel of schema.relations) {
      if (rel.cardinality === 'N:M') continue;
      const isReverse = rel.cardinality === 'N:1';
      const fkTableId = isReverse ? rel.sourceTableId : rel.targetTableId;
      const refTableId = isReverse ? rel.targetTableId : rel.sourceTableId;
      const fkColIds = isReverse
        ? (rel.sourceColumnIds?.length ? rel.sourceColumnIds : [rel.sourceColumnId])
        : (rel.targetColumnIds?.length ? rel.targetColumnIds : [rel.targetColumnId]);
      const refColIds = isReverse
        ? (rel.targetColumnIds?.length ? rel.targetColumnIds : [rel.targetColumnId])
        : (rel.sourceColumnIds?.length ? rel.sourceColumnIds : [rel.sourceColumnId]);

      if (fkTableId !== tableId) continue;
      const refTable = tableMap.get(refTableId);
      const fkTable = tableMap.get(fkTableId);
      if (!refTable || !fkTable) continue;
      const srcCols = refColIds
        .map((id) => refTable.columns.find((c) => c.id === id))
        .filter((c): c is Column => Boolean(c));
      const tgtCols = fkColIds
        .map((id) => fkTable.columns.find((c) => c.id === id))
        .filter((c): c is Column => Boolean(c));
      if (srcCols.length === 0 || srcCols.length !== tgtCols.length) continue;
      result.push({ rel, srcTable: refTable, srcCols, tgtCols });
    }
    return result;
  };

  schema.tables.forEach((table) => {
    const tblName = formatTableName(table, dialect, quoteIdentifiers);
    const mssqlSchema = (table.schema || 'dbo').trim() || 'dbo';

    if (includeComments && table.comment && dialect === 'general') {
      lines.push(`-- ${table.comment}`);
    }

    lines.push(`CREATE TABLE ${tblName} (`);

    const pkCols = table.columns.filter((c) => c.isPrimaryKey);
    const isSinglePk = pkCols.length === 1;
    const colDefs: string[] = [];

    table.columns.forEach((col) => {
      const converted = formatTypeForEngine(col.type, col.isAutoIncrement, dialect);
      const colTypeSql =
        dialect === 'postgresql' ? converted.type.toUpperCase() : converted.type;
      const parts: string[] = [];
      parts.push(`  ${quoteId(col.name, dialect, quoteIdentifiers)}`);
      parts.push(colTypeSql);

      // Engine-specific auto-increment / identity syntax
      if (converted.isAutoIncrement) {
        if (dialect === 'mssql') {
          parts.push('IDENTITY(1,1)');
        } else if (dialect === 'mysql') {
          parts.push('AUTO_INCREMENT');
        } else if (dialect === 'general') {
          parts.push('GENERATED BY DEFAULT AS IDENTITY');
        }
      }

      if (isSinglePk && col.isPrimaryKey) {
        parts.push('PRIMARY KEY');
      }

      if (!col.isNullable && !(isSinglePk && col.isPrimaryKey)) {
        parts.push('NOT NULL');
      }

      if (col.isUnique && !col.isPrimaryKey) {
        parts.push('UNIQUE');
      }

      const def = convertDefaultValueForEngine(col.defaultValue, dialect);
      if (def) {
        parts.push(`DEFAULT ${def}`);
      }

      if (col.checkConstraint.trim()) {
        parts.push(`CHECK (${col.checkConstraint.trim()})`);
      }

      if (includeComments && col.comment && dialect === 'mysql') {
        parts.push(`COMMENT '${escapeSqlString(col.comment)}'`);
      }

      colDefs.push(parts.join(' '));
    });

    if (pkCols.length > 1) {
      const pkList = pkCols
        .map((c) => quoteId(c.name, dialect, quoteIdentifiers))
        .join(', ');
      colDefs.push(`  PRIMARY KEY (${pkList})`);
    }

    if (table.uniqueConstraints && table.uniqueConstraints.length > 0) {
      const colById = new Map(table.columns.map((c) => [c.id, c]));
      table.uniqueConstraints.forEach((uq) => {
        const uqCols = uq.columns
          .map((cid) => colById.get(cid))
          .filter((c): c is Column => Boolean(c));
        if (uqCols.length === 0) return;
        const uqList = uqCols.map((c) => quoteId(c.name, dialect, quoteIdentifiers)).join(', ');
        const uqName = uq.name.trim()
          ? `CONSTRAINT ${quoteId(uq.name.trim(), dialect, quoteIdentifiers)} `
          : '';
        colDefs.push(`  ${uqName}UNIQUE (${uqList})`);
      });
    }

    if (table.checkConstraints && table.checkConstraints.length > 0) {
      table.checkConstraints.forEach((chk) => {
        if (!chk.expression.trim()) return;
        const chkName = chk.name.trim()
          ? `CONSTRAINT ${quoteId(chk.name.trim(), dialect, quoteIdentifiers)} `
          : '';
        colDefs.push(`  ${chkName}CHECK (${chk.expression.trim()})`);
      });
    }

    const tableFks = getFkForTable(table.id);
    tableFks.forEach(({ rel, srcTable, srcCols, tgtCols }) => {
      const constraintName = quoteId(
        rel.name || `fk_${table.name}_${tgtCols[0].name}`,
        dialect,
        quoteIdentifiers
      );
      const refTblName = formatTableName(srcTable, dialect, quoteIdentifiers);
      const onDelete = profile.referentialActions.includes(rel.onDelete)
        ? rel.onDelete
        : 'NO ACTION';
      const onUpdate = profile.referentialActions.includes(rel.onUpdate)
        ? rel.onUpdate
        : 'NO ACTION';
      const tgtColsSql = tgtCols.map((c) => quoteId(c.name, dialect, quoteIdentifiers)).join(', ');
      const srcColsSql = srcCols.map((c) => quoteId(c.name, dialect, quoteIdentifiers)).join(', ');

      alterFkStatements.push(
        `ALTER TABLE ${tblName}\n  ADD CONSTRAINT ${constraintName}\n  FOREIGN KEY (${tgtColsSql})\n  REFERENCES ${refTblName} (${srcColsSql})\n  ON DELETE ${onDelete}\n  ON UPDATE ${onUpdate};`
      );
    });

    lines.push(colDefs.join(',\n'));

    if (dialect === 'mysql') {
      const engineClause = `ENGINE=${table.storageEngine || 'InnoDB'}`;
      const charsetClause = `DEFAULT CHARSET=${table.charset || 'utf8mb4'}`;
      const commentClause =
        includeComments && table.comment
          ? ` COMMENT='${escapeSqlString(table.comment)}'`
          : '';
      lines.push(`) ${engineClause} ${charsetClause}${commentClause};`);
    } else {
      lines.push(');');
    }

    if (dialect === 'postgresql' && includeComments) {
      if (table.comment) {
        lines.push(`COMMENT ON TABLE ${tblName} IS '${escapeSqlString(table.comment)}';`);
      }
      table.columns.forEach((col) => {
        if (col.comment) {
          lines.push(
            `COMMENT ON COLUMN ${tblName}.${quoteId(
              col.name,
              dialect,
              quoteIdentifiers
            )} IS '${escapeSqlString(col.comment)}';`
          );
        }
      });
    }

    if (dialect === 'mssql' && includeComments) {
      if (table.comment) {
        lines.push(
          `EXEC sp_addextendedproperty @name = N'MS_Description', @value = N'${escapeSqlString(
            table.comment
          )}', @level0type = N'SCHEMA', @level0name = N'${escapeSqlString(
            mssqlSchema
          )}', @level1type = N'TABLE', @level1name = N'${escapeSqlString(table.name)}';`
        );
      }
      table.columns.forEach((col) => {
        if (col.comment) {
          lines.push(
            `EXEC sp_addextendedproperty @name = N'MS_Description', @value = N'${escapeSqlString(
              col.comment
            )}', @level0type = N'SCHEMA', @level0name = N'${escapeSqlString(
              mssqlSchema
            )}', @level1type = N'TABLE', @level1name = N'${escapeSqlString(
              table.name
            )}', @level2type = N'COLUMN', @level2name = N'${escapeSqlString(col.name)}';`
          );
        }
      });
    }

    if (table.indexes && table.indexes.length > 0) {
      const colById = new Map(table.columns.map((c) => [c.id, c]));
      table.indexes.forEach((idx) => {
        const idxCols = idx.columns
          .map((cid) => colById.get(cid))
          .filter((c): c is Column => Boolean(c));
        if (!idx.name.trim() || idxCols.length === 0) return;
        const uniqueKw = idx.isUnique ? 'UNIQUE ' : '';
        const idxName = quoteId(idx.name.trim(), dialect, quoteIdentifiers);
        const colsList = idxCols
          .map((c) => quoteId(c.name, dialect, quoteIdentifiers))
          .join(', ');
        const includeCols = (idx.includeColumns || [])
          .map((cid) => colById.get(cid))
          .filter((c): c is Column => Boolean(c));
        const includeClause =
          includeCols.length > 0 && (dialect === 'postgresql' || dialect === 'mssql')
            ? ` INCLUDE (${includeCols.map((c) => quoteId(c.name, dialect, quoteIdentifiers)).join(', ')})`
            : '';
        const whereClause =
          idx.whereClause?.trim() && (dialect === 'postgresql' || dialect === 'mssql')
            ? ` WHERE ${idx.whereClause.trim()}`
            : '';

        if (dialect === 'postgresql' && idx.method?.trim()) {
          indexStatements.push(
            `CREATE ${uniqueKw}INDEX ${idxName} ON ${tblName} USING ${idx.method.trim()} (${colsList})${includeClause}${whereClause};`
          );
        } else if (
          dialect === 'mysql' &&
          (idx.method?.toUpperCase() === 'FULLTEXT' || idx.method?.toUpperCase() === 'SPATIAL')
        ) {
          indexStatements.push(
            `CREATE ${idx.method.toUpperCase()} INDEX ${idxName} ON ${tblName} (${colsList});`
          );
        } else {
          indexStatements.push(
            `CREATE ${uniqueKw}INDEX ${idxName} ON ${tblName} (${colsList})${includeClause}${whereClause};`
          );
        }
      });
    }

    if (dialect === 'mssql') {
      lines.push('GO');
    }

    lines.push('');
  });

  // Junction tables for N:M relations
  schema.relations
    .filter((r) => r.cardinality === 'N:M')
    .forEach((rel) => {
      const srcTable = tableMap.get(rel.sourceTableId);
      const tgtTable = tableMap.get(rel.targetTableId);
      if (!srcTable || !tgtTable) return;
      const srcCol = srcTable.columns.find((c) => c.id === rel.sourceColumnId);
      const tgtCol = tgtTable.columns.find((c) => c.id === rel.targetColumnId);
      if (!srcCol || !tgtCol) return;

      const joinBaseName = `${srcTable.name}_${tgtTable.name}`;
      const joinTablePseudo: Table = {
        ...srcTable,
        name: joinBaseName,
      };
      const joinName = formatTableName(joinTablePseudo, dialect, quoteIdentifiers);
      const srcRefName = formatTableName(srcTable, dialect, quoteIdentifiers);
      const tgtRefName = formatTableName(tgtTable, dialect, quoteIdentifiers);

      const colA = `${srcTable.name}_${srcCol.name}`;
      const colB = `${tgtTable.name}_${tgtCol.name}`;
      const typeA = formatTypeForEngine(srcCol.type, false, dialect).type;
      const typeB = formatTypeForEngine(tgtCol.type, false, dialect).type;
      const onDelete = profile.referentialActions.includes(rel.onDelete)
        ? rel.onDelete
        : 'NO ACTION';
      const onUpdate = profile.referentialActions.includes(rel.onUpdate)
        ? rel.onUpdate
        : 'NO ACTION';

      const stmtLines = [
        `-- Many-to-Many join table for ${srcTable.name} <-> ${tgtTable.name}`,
        `CREATE TABLE ${joinName} (`,
        `  ${quoteId(colA, dialect, quoteIdentifiers)} ${
          dialect === 'postgresql' ? typeA.toUpperCase() : typeA
        } NOT NULL,`,
        `  ${quoteId(colB, dialect, quoteIdentifiers)} ${
          dialect === 'postgresql' ? typeB.toUpperCase() : typeB
        } NOT NULL,`,
        `  PRIMARY KEY (${quoteId(colA, dialect, quoteIdentifiers)}, ${quoteId(
          colB,
          dialect,
          quoteIdentifiers
        )}),`,
        `  FOREIGN KEY (${quoteId(
          colA,
          dialect,
          quoteIdentifiers
        )}) REFERENCES ${srcRefName} (${quoteId(
          srcCol.name,
          dialect,
          quoteIdentifiers
        )}) ON DELETE ${onDelete} ON UPDATE ${onUpdate},`,
        `  FOREIGN KEY (${quoteId(
          colB,
          dialect,
          quoteIdentifiers
        )}) REFERENCES ${tgtRefName} (${quoteId(
          tgtCol.name,
          dialect,
          quoteIdentifiers
        )}) ON DELETE ${onDelete} ON UPDATE ${onUpdate}`,
        dialect === 'mysql' ? `) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;` : `);`,
      ];
      if (dialect === 'mssql') stmtLines.push('GO');

      joinTableStatements.push(stmtLines.join('\n'));
    });

  if (joinTableStatements.length > 0) {
    lines.push('-- Junction Tables (N:M Relationships)');
    lines.push(joinTableStatements.join('\n\n'));
    lines.push('');
  }

  if (alterFkStatements.length > 0) {
    lines.push('-- Foreign Key Constraints');
    lines.push(alterFkStatements.join('\n\n'));
    if (dialect === 'mssql') {
      lines.push('GO');
    }
    lines.push('');
  }

  if (indexStatements.length > 0) {
    lines.push('-- Indexes');
    lines.push(indexStatements.join('\n'));
    if (dialect === 'mssql') {
      lines.push('GO');
    }
    lines.push('');
  }

  return lines.join('\n').trim() + '\n';
}

export function generateJsonSchema(schema: SchemaModel): string {
  const payload = {
    format: 'schemaforge/v1',
    exportedAt: new Date().toISOString(),
    schema: {
      id: schema.id,
      name: schema.name,
      engine: schema.engine || 'postgresql',
      description: schema.description,
      tables: schema.tables.map((t) => ({
        ...t,
        codeGen: normalizeTableCodeGen(t.codeGen),
      })),
      relations: schema.relations,
    },
  };
  return JSON.stringify(payload, null, 2);
}

const VALID_ENGINES = new Set<DatabaseEngine>(['postgresql', 'mssql', 'mysql', 'general']);

export function parseImportedJsonSchema(jsonText: string): { model?: SchemaModel; error?: string } {
  try {
    const parsed = JSON.parse(jsonText);
    const candidate = parsed?.schema ?? parsed;

    if (!candidate || typeof candidate !== 'object') {
      return { error: 'JSON root must contain a valid schema object.' };
    }
    if (!Array.isArray(candidate.tables) || !Array.isArray(candidate.relations)) {
      return { error: 'Schema JSON must include "tables" and "relations" arrays.' };
    }

    const engine: DatabaseEngine = VALID_ENGINES.has(candidate.engine)
      ? candidate.engine
      : 'postgresql';
    const defaultSchema = ENGINE_PROFILES[engine].defaultSchema;

    const tables: Table[] = candidate.tables.map((t: Partial<Table>, idx: number) => ({
      id: typeof t.id === 'string' && t.id ? t.id : `tbl-import-${idx}-${Date.now()}`,
      name: typeof t.name === 'string' && t.name ? t.name : `table_${idx + 1}`,
      schema: typeof t.schema === 'string' ? t.schema : defaultSchema,
      storageEngine: t.storageEngine,
      charset: t.charset,
      codeGen: normalizeTableCodeGen(t.codeGen),
      color: t.color || 'blue',
      comment: typeof t.comment === 'string' ? t.comment : '',
      x: typeof t.x === 'number' && Number.isFinite(t.x) ? t.x : 80 + idx * 320,
      y: typeof t.y === 'number' && Number.isFinite(t.y) ? t.y : 80,
      columns: Array.isArray(t.columns)
        ? t.columns.map((c: Partial<Column>, cIdx: number) => ({
            id: typeof c.id === 'string' && c.id ? c.id : `col-${idx}-${cIdx}-${Date.now()}`,
            name: typeof c.name === 'string' && c.name ? c.name : `column_${cIdx + 1}`,
            type:
              typeof c.type === 'string' && c.type
                ? c.type
                : ENGINE_PROFILES[engine].defaultStringType,
            isPrimaryKey: Boolean(c.isPrimaryKey),
            isNullable: c.isNullable !== undefined ? Boolean(c.isNullable) : true,
            isUnique: Boolean(c.isUnique),
            isAutoIncrement: Boolean(c.isAutoIncrement),
            defaultValue: typeof c.defaultValue === 'string' ? c.defaultValue : '',
            checkConstraint: typeof c.checkConstraint === 'string' ? c.checkConstraint : '',
            comment: typeof c.comment === 'string' ? c.comment : '',
          }))
        : [],
      indexes: Array.isArray(t.indexes)
        ? t.indexes.map((ix: Partial<TableIndex>, ixIdx: number) => ({
            id: typeof ix.id === 'string' && ix.id ? ix.id : `idx-${idx}-${ixIdx}-${Date.now()}`,
            name: typeof ix.name === 'string' ? ix.name : `idx_${idx}_${ixIdx + 1}`,
            columns: Array.isArray(ix.columns)
              ? ix.columns.filter((cid): cid is string => typeof cid === 'string')
              : [],
            isUnique: Boolean(ix.isUnique),
            method: typeof ix.method === 'string' ? ix.method : undefined,
            whereClause: typeof ix.whereClause === 'string' ? ix.whereClause : undefined,
            includeColumns: Array.isArray(ix.includeColumns)
              ? ix.includeColumns.filter((cid): cid is string => typeof cid === 'string')
              : undefined,
          }))
        : [],
      uniqueConstraints: Array.isArray(t.uniqueConstraints)
        ? t.uniqueConstraints.map((uq: Partial<TableUniqueConstraint>, uqIdx: number) => ({
            id: typeof uq.id === 'string' && uq.id ? uq.id : `uq-${idx}-${uqIdx}-${Date.now()}`,
            name: typeof uq.name === 'string' ? uq.name : `uq_${idx}_${uqIdx + 1}`,
            columns: Array.isArray(uq.columns)
              ? uq.columns.filter((cid): cid is string => typeof cid === 'string')
              : [],
          }))
        : undefined,
      checkConstraints: Array.isArray(t.checkConstraints)
        ? t.checkConstraints.map((chk: Partial<TableCheckConstraint>, chkIdx: number) => ({
            id: typeof chk.id === 'string' && chk.id ? chk.id : `chk-${idx}-${chkIdx}-${Date.now()}`,
            name: typeof chk.name === 'string' ? chk.name : `chk_${idx}_${chkIdx + 1}`,
            expression: typeof chk.expression === 'string' ? chk.expression : '',
          }))
        : undefined,
    }));

    const validTableIds = new Set(tables.map((t) => t.id));
    const relations: Relation[] = candidate.relations
      .filter(
        (r: Partial<Relation>) =>
          r.sourceTableId &&
          r.targetTableId &&
          validTableIds.has(r.sourceTableId) &&
          validTableIds.has(r.targetTableId)
      )
      .map((r: Partial<Relation>, rIdx: number) => ({
        id: typeof r.id === 'string' && r.id ? r.id : `rel-import-${rIdx}-${Date.now()}`,
        name: typeof r.name === 'string' ? r.name : `fk_relation_${rIdx + 1}`,
        sourceTableId: r.sourceTableId!,
        sourceColumnId: r.sourceColumnId || '',
        targetTableId: r.targetTableId!,
        targetColumnId: r.targetColumnId || '',
        sourceColumnIds: Array.isArray(r.sourceColumnIds)
          ? r.sourceColumnIds.filter((cid): cid is string => typeof cid === 'string')
          : undefined,
        targetColumnIds: Array.isArray(r.targetColumnIds)
          ? r.targetColumnIds.filter((cid): cid is string => typeof cid === 'string')
          : undefined,
        cardinality: r.cardinality || '1:N',
        onDelete: r.onDelete || 'CASCADE',
        onUpdate: r.onUpdate || 'CASCADE',
      }));

    return {
      model: {
        id: typeof candidate.id === 'string' ? candidate.id : `schema-${Date.now()}`,
        name:
          typeof candidate.name === 'string' && candidate.name
            ? candidate.name
            : 'imported_schema',
        engine,
        description: typeof candidate.description === 'string' ? candidate.description : '',
        updatedAt: new Date().toISOString(),
        tables,
        relations,
      },
    };
  } catch (err) {
    return { error: err instanceof Error ? err.message : 'Invalid JSON syntax.' };
  }
}

export function downloadTextFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
